#!/usr/bin/env python3
"""Extract the hand-authored tear contours from the committed SVGs into a
TypeScript module for the Skia sheet.

The contours are the single source of truth in
assets/tears/tear-a-{top,bottom}.svg (originally authored point tables in
preserved/torn-paper-web/generators/author_tears.py — NEVER regenerate
them). Metro cannot require() an SVG on native, so this script copies the
path's point table VERBATIM into src/tearContours.ts; it does not smooth,
resample or otherwise touch the data. Re-run only if the SVG is ever
retouched upstream:

    python3 scripts/extract_contours.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "tears"
OUT = ROOT / "src" / "tearContours.ts"


def contour(svg_name: str) -> list[float]:
    d = re.search(r'd="([^"]+)"', (ASSETS / svg_name).read_text()).group(1)
    pairs = re.findall(r"(-?\d+\.?\d*),(-?\d+\.?\d*)", d)
    pts = [(float(a), float(b)) for a, b in pairs]
    contour = [p[1] for p in pts[1:-1]]  # drop the two closing corners
    assert len(contour) == 801, f"{svg_name}: {len(contour)} points, want 801"
    assert contour[0] == contour[-1], f"{svg_name}: first/last y differ — the tile would seam"
    return contour


def main() -> int:
    top = contour("tear-a-top.svg")
    bottom = contour("tear-a-bottom.svg")
    OUT.write_text(
        "// GENERATED by scripts/extract_contours.py from assets/tears/\n"
        "// tear-a-{top,bottom}.svg — do not edit. The point tables are the\n"
        "// hand-authored contours (author_tears.py); this module copies them\n"
        "// verbatim because Metro cannot require() an SVG on native.\n"
        f"export const TEAR_A_TOP: number[] =\n  {json.dumps(top)};\n\n"
        f"export const TEAR_A_BOTTOM: number[] =\n  {json.dumps(bottom)};\n"
    )
    print(f"wrote {OUT} ({len(top)} + {len(bottom)} points, endpoints match)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
